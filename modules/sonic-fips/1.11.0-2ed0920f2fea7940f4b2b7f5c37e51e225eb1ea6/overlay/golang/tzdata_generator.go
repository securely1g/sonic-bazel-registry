// Preserve cmd/dist/buildgo.go's byte-stable Go string encoding for zoneinfo.zip.
package main

import (
	"fmt"
	"os"
	"strings"
)

func main() {
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	var out strings.Builder
	out.WriteByte('"')
	const hex = "0123456789abcdef"
	for _, c := range data {
		if c >= 0x20 && c <= 0x7e && c != '"' && c != '\\' {
			out.WriteByte(c)
		} else {
			out.WriteString(`\x`)
			out.WriteByte(hex[c>>4])
			out.WriteByte(hex[c&15])
		}
	}
	out.WriteByte('"')
	fmt.Printf("// Code generated by go tool dist; DO NOT EDIT.\n\npackage tzdata\nconst zipdata = %s\n", out.String())
}
